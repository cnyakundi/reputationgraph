from __future__ import annotations

from html import escape

from reputationgraph.models import AnalysisResult


def render_html(result: AnalysisResult) -> str:
    cards = []
    for item in result.narratives:
        evidence = "".join(f"<li>{escape(line)}</li>" for line in item.explanation)
        citations = "".join(
            f'<li><a href="{escape(str(citation.url), quote=True)}" '
            f'rel="noopener noreferrer">{escape(citation.title)}</a> '
            f'<span class="source">— {escape(citation.source)}, '
            f'{citation.published_at:%Y-%m-%d}</span></li>'
            for citation in item.evidence
        )
        cards.append(
            f"""<article><div class="row"><h2>{escape(item.name.title())}</h2>
            <span class="badge {item.severity}">{item.severity} · {item.risk_score}</span></div>
            <p>Sources: {escape(', '.join(item.sources))}</p><ul>{evidence}</ul>
            <h3>Evidence</h3><ul class="citations">{citations}</ul></article>"""
        )
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{escape(result.subject)} · ReputationGraph</title><style>
:root{{--ink:#172033;--muted:#667085;--paper:#f4f7fb;--card:#fff;--accent:#6855d9}}
*{{box-sizing:border-box}}body{{margin:0;background:var(--paper);color:var(--ink);font:16px/1.5 system-ui}}
main{{max-width:920px;margin:0 auto;padding:56px 24px}}header{{background:#17152b;color:white;padding:34px;border-radius:20px}}
.eyebrow{{color:#b7adff;text-transform:uppercase;letter-spacing:.12em;font-size:12px}}h1{{font-size:42px;margin:.2em 0}}
.score{{font-size:64px;font-weight:750;color:#d8d3ff}}.meta{{color:#c9c7d4}}article{{background:var(--card);margin:20px 0;padding:26px;border-radius:16px;box-shadow:0 8px 30px #1b234012}}
.row{{display:flex;justify-content:space-between;gap:16px;align-items:center}}h2{{margin:0}}.badge{{border-radius:999px;padding:7px 12px;font-weight:650}}
.low{{background:#dcfae6;color:#067647}}.moderate{{background:#fef0c7;color:#93370d}}.high{{background:#fee4e2;color:#b42318}}.critical{{background:#b42318;color:white}}
.citations a{{color:#4b3bc4;font-weight:650}}.source{{color:var(--muted)}}
footer{{color:var(--muted);margin-top:34px;font-size:14px}}@media(max-width:600px){{h1{{font-size:32px}}.row{{display:block}}}}
</style></head><body><main><header><div class="eyebrow">Reputation intelligence brief</div>
<h1>{escape(result.subject)}</h1><div class="score">{result.overall_risk}</div>
<div class="meta">Overall risk · {result.mention_count} mentions · generated {result.generated_at:%Y-%m-%d %H:%M UTC}</div></header>
<section>{''.join(cards)}</section><footer>Generated by ReputationGraph. Scores are decision support, not statements of fact. Review the cited source evidence.</footer>
</main></body></html>"""
